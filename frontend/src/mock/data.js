function roundTo(value, base) {
  return Math.max(base, Math.round(value / base) * base)
}

export const lots = []
export const bids = []

for (const [category, subs] of Object.entries(catalog)) {
  for (const [subcategory, list] of Object.entries(subs)) {
    for (const [title, startPrice, description] of list) {
      const id = lots.length + 1
      const authorId = randomInt(1, users.length)
      const step = startPrice >= 5000 ? roundTo(startPrice * 0.05, 100) : roundTo(startPrice * 0.08, 50)

      const roll = random()
      let status = 'active'
      if (roll > 0.9) status = 'cancelled'
      else if (roll > 0.75) status = 'finished'

      let createdAt
      let endsAt
      if (status === 'finished') {
        endsAt = now - randomInt(1, 96) * hour
        createdAt = endsAt - randomInt(24, 120) * hour
      } else {
        createdAt = now - randomInt(1, 96) * hour
        endsAt = now + randomInt(15, 6 * 24 * 60) * minute
      }

      lots.push({
        id,
        title,
        description,
        image: `https://picsum.photos/seed/dorm-lot-${id}/600/400`,
        category,
        subcategory,
        authorId,
        startPrice,
        step,
        createdAt,
        endsAt,
        status
      })

      if (status === 'cancelled' || random() < 0.35) continue

      const count = randomInt(1, 6)
      const until = Math.min(now, endsAt)
      let amount = startPrice
      let time = createdAt
      let lastBidder = null
      for (let i = 0; i < count; i++) {
        amount += step * randomInt(1, 3)
        time += Math.floor((until - time) * random() * 0.6)
        let bidder = randomInt(1, users.length)
        while (bidder === authorId || bidder === lastBidder) {
          bidder = randomInt(1, users.length)
        }
        lastBidder = bidder
        bids.push({ id: bids.length + 1, lotId: id, userId: bidder, amount, createdAt: time })
      }
    }
  }
}
